/**
 * Generate a recovery-recipe vector by driving the SDK's real reconstitution.
 *
 *   PLEXUS_SDK=/path/to/plexus-sdk-ts/dist/index.js node gen-recovery-vector.mjs
 *
 * A recovery recipe is what makes a fleet rebuildable without the provisioning
 * server: derivation paths and per-slot high-water marks, never key material.
 * The Zig plane must both PRODUCE one the SDK accepts and CONSUME one the SDK
 * produced, so this records the SDK's actual behaviour on four payloads:
 *
 *   honest    what an exporter should emit
 *   poisoned  currentIndex BELOW the paths replayed beside it. The recovery
 *             service does not authenticate its callers, so this is a reachable
 *             input, not a malformed-payload hypothetical. Trusting it rewinds
 *             the allocator beneath live certificates and — because a certId is
 *             deterministic in (parent, resourceId, domainFlag, childIndex) —
 *             the next derivations reproduce a live holder's key exactly.
 *   omitted   no functionalDomains row at all for a triple the paths prove. The
 *             same rewind, by omission.
 *   burned    currentIndex ABOVE the paths, which is what a rotation leaves
 *             behind. The floor must not drag it back down.
 *
 * The expected values are whatever the SDK returned, so the Zig side is checked
 * against the oracle rather than against my reading of the recipe format.
 */

import { writeFileSync } from "node:fs";

const SDK =
  process.env.PLEXUS_SDK ??
  "/Users/toddprice/projects/repos/libs/plexus-sdk-ts/dist/index.js";
const { PlexusClient, MemoryKeyStore } = await import(SDK);
const { reconstituteFromRecoveryExport } = await import(
  SDK.replace(/index\.js$/, "modules/recovery/reconstituteFromRecoveryExport.js")
);

const EMAIL = "fleet-recovery@example.test";
const SALT = "recovery-vector-salt-v1";
const RESOURCE = "member";
const FLAG = 6; // CHILD_CREATION

// Provision a small fleet so the paths below describe real, derivable nodes.
const origin = new PlexusClient({ mode: "memory", rootEmail: EMAIL, rootSalt: SALT, broadcaster: "none" });
const root = await origin.registerIdentity();
const kids = [];
for (let i = 0; i < 4; i++) {
  kids.push(await origin.deriveChild(root.certId, RESOURCE, FLAG));
}
await origin.close();

const tenantPaths = kids.map((k) => ({
  certId: k.certId,
  resourceId: RESOURCE,
  parentCertId: root.certId,
  steps: [
    { tenantType: 0, childIndex: k.childIndex, resourceId: RESOURCE, domainFlag: FLAG },
  ],
}));

const domainRow = (currentIndex) => ({
  certId: root.certId,
  resourceId: RESOURCE,
  parentCertId: root.certId,
  domainFlag: FLAG,
  currentIndex,
  algorithmVersion: "plexus-kdf-v1",
});

const basePayload = (functionalDomains) => ({
  schemaVersion: "v1",
  certId: root.certId,
  email: EMAIL,
  resourceRegistrations: [],
  functionalDomains,
  edges: [],
  tenantPaths,
  algorithmVersions: [],
});

const cases = [
  { label: "honest", functionalDomains: [domainRow(4)] },
  { label: "poisoned", functionalDomains: [domainRow(2)] },
  { label: "omitted", functionalDomains: [] },
  { label: "burned", functionalDomains: [domainRow(9)] },
  // Sibling rows for one triple must reduce to their maximum, not to the last
  // one written — the export orders rows by insertion time, which bears no
  // relation to index magnitude.
  { label: "siblings-unordered", functionalDomains: [domainRow(7), domainRow(3)] },
];

const results = [];
for (const c of cases) {
  const store = new MemoryKeyStore();
  const payload = basePayload(c.functionalDomains);
  const out = await reconstituteFromRecoveryExport({
    store,
    rootEmail: EMAIL,
    rootSalt: SALT,
    payload,
  });
  results.push({
    label: c.label,
    functionalDomains: c.functionalDomains,
    certId: out.certId,
    reconstituted: out.reconstituted,
    // The number that matters: what the rebuilt store hands out next.
    nextAllocation: await store.incrementChildIndex(root.certId, RESOURCE, FLAG),
  });
}

const out = {
  _comment:
    "GENERATED by gen-recovery-vector.mjs by driving the SDK's real " +
    "reconstituteFromRecoveryExport. Do not hand-edit. nextAllocation is what " +
    "the rebuilt store actually handed out.",
  schemaVersion: 1,
  oracle: "@dusk-inc/plexus-sdk reconstituteFromRecoveryExport",
  generator: "vectors/gen-recovery-vector.mjs",
  universe: { rootEmail: EMAIL, rootSalt: SALT },
  resourceId: RESOURCE,
  domainFlag: FLAG,
  rootCertId: root.certId,
  provisioned: kids.map((k) => ({
    certId: k.certId,
    childIndex: k.childIndex,
    derivationPath: k.derivationPath,
    publicKey: k.publicKey,
  })),
  tenantPaths,
  cases: results,
};

const path = new URL("./recovery.golden.json", import.meta.url);
writeFileSync(path, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${results.length} recovery cases -> ${path.pathname}`);
for (const r of results) {
  console.log(`  ${r.label.padEnd(20)} nextAllocation=${r.nextAllocation}`);
}
