/**
 * Generate a capability-cert vector from the TypeScript fleet plane.
 *
 *   PLEXUS_SDK=/path/to/plexus-sdk-ts/dist/index.js node gen-cert-vector.mjs
 *
 * M4's gate was "a cert issued by the Zig plane is byte-identical to one the
 * TypeScript plane issues for the same unit". That holds for the 66-byte payload
 * and the 1024-byte cell, and it does NOT hold for the signature — see the note
 * below, which is why this vector separates them.
 *
 * `validFromMs` is pinned rather than taken from the clock, because it lands in
 * both the payload and the cell header. A vector generated from `Date.now()`
 * would be unreproducible by construction.
 *
 * ## Why the signature is not compared byte-for-byte
 *
 * Both sides are deterministic and neither uses randomness, but they derive the
 * ECDSA nonce differently: @bsv/sdk runs its own HMAC-DRBG (RFC-6979), while
 * bsvz delegates to Zig's `std.crypto.sign.ecdsa`, whose deterministic scheme is
 * its own. Same key, same digest, different valid signature. Measured, not
 * assumed — see spike/src/sigcmp.zig.
 *
 * That is not a defect. The nonce construction is an implementation detail; the
 * wire contract is "a low-S signature over sha256(cell) that verifies against
 * the operator pubkey". So the vector carries the signature for the TS side to
 * be verified by the Zig side, and vice versa — interoperability, which is the
 * property that actually matters, rather than byte equality, which is not.
 */

import { writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { Fleet } from "../../fleet/fleet.js";
import { openPlexusDeriver } from "../../fleet/plexus-deriver.js";

const ROOT_EMAIL = "operator@fleet.example";
const ROOT_SALT = "cert-vector-salt-v1";
/** Pinned so the vector is reproducible; it lands in the payload AND the cell. */
const VALID_FROM_MS = 1_767_225_600_000n; // 2026-01-01T00:00:00Z
const NO_EXPIRY = 0xffffffffffffffffn;

const hex = (u8) => Buffer.from(u8).toString("hex");

const deriver = await openPlexusDeriver({
  rootEmail: ROOT_EMAIL,
  rootSalt: ROOT_SALT,
});
const fleet = new Fleet({ deriver });

const anchor = await fleet.operatorPublicKey();
const zone = await fleet.addZone("North Depot");
const node = await deriver.derive(zone.certId, "device", "cold-chain-01");
const unit = await fleet.issueCert(node, NO_EXPIRY, VALID_FROM_MS);

// A SECOND cert with a real, non-maximal expiry. The default expiry is
// UINT64_MAX, whose eight 0xff bytes are identical in either endianness — so a
// vector carrying only that value cannot catch a byte-order mistake in the
// expiry field. This one has distinguishable bytes in every octet.
const REAL_EXPIRY_MS = 0x0123456789abcdefn;
const node2 = await deriver.derive(zone.certId, "device", "cold-chain-02");
const unit2 = await fleet.issueCert(node2, REAL_EXPIRY_MS, VALID_FROM_MS);

const out = {
  _comment:
    "GENERATED by gen-cert-vector.mjs from the TypeScript fleet plane. " +
    "Do not hand-edit. payload and cell are byte-identical targets; the " +
    "signature is NOT (different deterministic nonce schemes) and is carried " +
    "here to be VERIFIED by the other side.",
  schemaVersion: 1,
  oracle: "tools/fleet (TypeScript)",
  generator: "vectors/gen-cert-vector.mjs",
  universe: { rootEmail: ROOT_EMAIL, rootSalt: ROOT_SALT },
  validFromMs: VALID_FROM_MS.toString(),
  expiryMs: NO_EXPIRY.toString(),
  operatorPubKeyHex: hex(anchor),
  zone: {
    label: zone.label,
    certId: zone.certId,
    derivationPath: zone.derivationPath,
    index: zone.index,
  },
  device: {
    label: node.label,
    certId: node.certId,
    publicKeyHex: hex(node.publicKey),
    derivationPath: node.derivationPath,
    index: node.index,
  },
  channelIdHex: hex(unit.channelId),
  certPayloadHex: hex(unit.certPayload),
  certHashHex: hex(unit.certHash),
  certCellHex: hex(unit.certCell),
  cellSha256Hex: createHash("sha256").update(Buffer.from(unit.certCell)).digest("hex"),
  certSigHex: hex(unit.certSig),
  realExpiryCase: {
    _why:
      "expiryMs here is not UINT64_MAX, so its byte order is observable. The " +
      "default no-expiry value is eight 0xff bytes and reads the same either way.",
    expiryMs: REAL_EXPIRY_MS.toString(),
    devicePublicKeyHex: hex(node2.publicKey),
    channelIdHex: hex(unit2.channelId),
    certPayloadHex: hex(unit2.certPayload),
    certCellHex: hex(unit2.certCell),
  },
};

await fleet.close();

const path = new URL("./cert.golden.json", import.meta.url);
writeFileSync(path, JSON.stringify(out, null, 2) + "\n");
console.log(
  `wrote cert vector -> ${path.pathname}\n` +
    `  payload ${unit.certPayload.length}B, cell ${unit.certCell.length}B, sig ${unit.certSig.length}B`,
);
