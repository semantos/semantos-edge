/**
 * Generate a rotation/allocation trace from the Plexus SDK's real KeyStore.
 *
 *   PLEXUS_SDK=/path/to/plexus-sdk-ts/dist/index.js node gen-rotation-vector.mjs
 *
 * M3's gate was "port the SDK's rotation tests and they pass unchanged in
 * meaning". Porting tests by hand re-asserts what I believe the semantics are.
 * Driving the actual store and recording what it returned asserts what they ARE
 * — so this replays a scripted sequence of allocations, burns and restores
 * against the SDK's MemoryKeyStore and captures every return value.
 *
 * The interesting semantics being captured:
 *
 *   - one allocator per (parentCertId, resourceId, domainFlag); the parent alone
 *     is NOT the key
 *   - a burn consumes an index without issuing it, so the next allocation lands
 *     strictly past anything already handed out
 *   - burning an untouched context still burns index 0
 *   - a restore may not rewind
 *   - derivation state mirrors the allocator rather than counting separately
 */

import { writeFileSync } from "node:fs";

const SDK =
  process.env.PLEXUS_SDK ??
  "/Users/toddprice/projects/repos/libs/plexus-sdk-ts/dist/index.js";
const { MemoryKeyStore } = await import(SDK);
if (typeof MemoryKeyStore !== "function") {
  throw new Error(`MemoryKeyStore not exported from ${SDK}`);
}

const P = "parent-a";
const Q = "parent-b";

/** The script. Each step names an op and its arguments; results are recorded. */
const script = [
  // A seat is taken, then vacated, then refilled — the joiner/leaver shape.
  { op: "allocate", parent: P, resource: "member", flag: 6 },
  { op: "burn", parent: P, resource: "member", flag: 6 },
  { op: "allocate", parent: P, resource: "member", flag: 6 },

  // Burning an untouched context still consumes index 0.
  { op: "burn", parent: P, resource: "fresh", flag: 6 },
  { op: "allocate", parent: P, resource: "fresh", flag: 6 },

  // Repeated burns each consume exactly one.
  { op: "burn", parent: P, resource: "member", flag: 6 },
  { op: "burn", parent: P, resource: "member", flag: 6 },
  { op: "allocate", parent: P, resource: "member", flag: 6 },

  // Isolation: a different resource, a different flag, a different parent.
  { op: "allocate", parent: P, resource: "device", flag: 6 },
  { op: "allocate", parent: P, resource: "member", flag: 2 },
  { op: "allocate", parent: Q, resource: "member", flag: 6 },

  // Recovery restores a high-water mark, then allocation resumes from it.
  { op: "restore", parent: Q, resource: "member", flag: 6, nextIndex: 9 },
  { op: "allocate", parent: Q, resource: "member", flag: 6 },
  { op: "allocate", parent: Q, resource: "member", flag: 6 },

  // A restore that would rewind must be refused.
  { op: "restore", parent: Q, resource: "member", flag: 6, nextIndex: 3, expectError: true },
  { op: "allocate", parent: Q, resource: "member", flag: 6 },

  // A restore to the current value is not a rewind.
  { op: "state", parent: P, resource: "member", flag: 6 },
  { op: "burn", parent: Q, resource: "member", flag: 6 },
  { op: "state", parent: Q, resource: "member", flag: 6 },
];

const store = new MemoryKeyStore();
const steps = [];

for (const s of script) {
  const entry = { ...s };
  try {
    switch (s.op) {
      case "allocate":
        entry.result = await store.incrementChildIndex(s.parent, s.resource, s.flag);
        break;
      case "burn":
        entry.result = await store.advanceInvoice(s.parent, s.resource, s.flag);
        break;
      case "restore":
        await store.setChildCounter(s.parent, s.resource, s.flag, s.nextIndex);
        entry.result = null;
        break;
      case "state": {
        const st = await store.getDerivationState(s.parent, s.resource, s.flag);
        entry.result = st === null ? null : st.currentIndex;
        break;
      }
      default:
        throw new Error(`unknown op ${s.op}`);
    }
    entry.threw = false;
  } catch (err) {
    entry.threw = true;
    entry.error = err.constructor.name;
  }
  steps.push(entry);
}

// Final state of every context the script touched, so a replay is checked on its
// end state and not only on each return value.
const contexts = [];
const seen = new Set();
for (const s of script) {
  const k = `${s.parent}|${s.resource}|${s.flag}`;
  if (seen.has(k)) continue;
  seen.add(k);
  const st = await store.getDerivationState(s.parent, s.resource, s.flag);
  contexts.push({
    parent: s.parent,
    resource: s.resource,
    flag: s.flag,
    currentIndex: st === null ? null : st.currentIndex,
    nextAllocation: await store.incrementChildIndex(s.parent, s.resource, s.flag),
  });
}

const out = {
  _comment:
    "GENERATED by gen-rotation-vector.mjs by driving the Plexus SDK's real " +
    "MemoryKeyStore. Do not hand-edit. Every result is what the SDK returned.",
  schemaVersion: 1,
  oracle: "@dusk-inc/plexus-sdk MemoryKeyStore",
  generator: "vectors/gen-rotation-vector.mjs",
  steps,
  finalContexts: contexts,
};

const path = new URL("./rotation.golden.json", import.meta.url);
writeFileSync(path, JSON.stringify(out, null, 2) + "\n");
console.log(
  `wrote ${steps.length} steps, ${contexts.length} contexts -> ${path.pathname}`,
);
