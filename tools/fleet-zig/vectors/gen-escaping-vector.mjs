/**
 * Generate escaping conformance cases from the Plexus SDK's own canonicalJson.
 *
 *   PLEXUS_SDK=/path/to/plexus-sdk-ts/dist/index.js node gen-escaping-vector.mjs
 *
 * The SDK's pinned derivation vector covers derivation thoroughly and covers
 * string escaping not at all: every value in its three certId cases is hex, an
 * email, or a dotted type name. No quote, no backslash, no control character, no
 * non-ASCII, no slash. A Zig port can therefore pass the whole vector while
 * being wrong for any operator-supplied resourceId — which is exactly the field
 * a fleet lets a human name.
 *
 * So these cases are generated, not invented: each expected string is whatever
 * the SDK actually produced, captured here so the Zig encoder is compared
 * against the oracle rather than against my reading of the ECMAScript spec.
 *
 * Surrogate handling is recorded but marked unrepresentable: a lone surrogate
 * has no well-formed UTF-8 encoding, so a Zig []const u8 cannot carry one in.
 * The divergence is unreachable from the port rather than merely untested.
 */

import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const SDK =
  process.env.PLEXUS_SDK ??
  "/Users/toddprice/projects/repos/libs/plexus-sdk-ts/dist/index.js";
const { canonicalJson } = await import(SDK);
if (typeof canonicalJson !== "function") {
  throw new Error(`canonicalJson not exported from ${SDK}`);
}

/** A preimage differing from a baseline only in the one string under test. */
const preimage = (fields) => ({
  subjectPublicKey: "02" + "aa".repeat(32),
  certifierPublicKey: "02" + "bb".repeat(32),
  type: "plexus.identity.derived",
  serialNumber: "cc".repeat(32),
  fields,
});

const utf8Representable = (s) => {
  // A lone surrogate survives a JS string but has no UTF-8 encoding; Buffer
  // replaces it with U+FFFD, so the round trip is lossy exactly there.
  return Buffer.from(s, "utf8").toString("utf8") === s;
};

const cases = [];
const add = (label, raw) => {
  const asValue = canonicalJson(preimage({ resourceId: raw }));
  const asKey = canonicalJson(preimage({ [raw]: "v" }));
  cases.push({
    label,
    // Bytes, so the Zig side reads an unambiguous input rather than parsing
    // escapes out of a JSON string and hoping the two agree.
    inputUtf8Hex: Buffer.from(raw, "utf8").toString("hex"),
    representableInUtf8: utf8Representable(raw),
    canonicalAsValue: asValue,
    canonicalAsKey: asKey,
  });
};

add("empty", "");
add("plain", "inbox");
add("double-quote", 'a"b');
add("backslash", "a\\b");
add("forward-slash", "a/b");
add("quote-and-backslash", '\\"');
for (let c = 0; c <= 0x1f; c++) {
  add(`c0-0x${c.toString(16).padStart(2, "0")}`, `a${String.fromCharCode(c)}b`);
}
add("del-0x7f", "a\x7fb");
add("two-byte-utf8", "café");
add("three-byte-utf8", "日本語");
add("four-byte-astral", "a😀b");
add("combining-mark", "é");
add("nbsp", "a b");
add("line-separator-u2028", "a b");
add("paragraph-separator-u2029", "a b");
add("lone-high-surrogate", "a\ud800b");
add("lone-low-surrogate", "a\udc00b");
add("colon-in-resource-id", "a:b");

// Multi-key cases: these exist to pin the SORT, which is UTF-16 code-unit order
// in JS and disagrees with UTF-8 byte order for astral vs U+E000..U+FFFF.
const sortCases = [];
const addSort = (label, keys) => {
  const fields = {};
  for (const k of keys) fields[k] = "v";
  sortCases.push({
    label,
    keysUtf8Hex: keys.map((k) => Buffer.from(k, "utf8").toString("hex")),
    canonical: canonicalJson(preimage(fields)),
  });
};
addSort("ascii-pair", ["b", "a"]);
addSort("astral-vs-private-use", ["\u{1F600}", "\uE000"]);
addSort("astral-vs-max-bmp", ["\u{10000}", "\uFFFF"]);
addSort("astral-pair", ["\u{1F600}", "\u{1F601}"]);
addSort("mixed", ["z", "\u{1F600}", "\uE000", "a"]);

const out = {
  _comment:
    "GENERATED by gen-escaping-vector.mjs from the Plexus SDK's canonicalJson. " +
    "Do not hand-edit. Covers the string-escaping surface the SDK's derivation " +
    "vector does not reach.",
  schemaVersion: 1,
  oracle: "@dusk-inc/plexus-sdk canonicalJson",
  generator: "vectors/gen-escaping-vector.mjs",
  baseline: preimage({ resourceId: "inbox" }),
  cases,
  sortCases,
};

const path = new URL("./canonical-json-escaping.golden.json", import.meta.url);
writeFileSync(path, JSON.stringify(out, null, 2) + "\n");
const unrepresentable = cases.filter((c) => !c.representableInUtf8).length;
console.log(
  `wrote ${cases.length} cases, ${sortCases.length} sort cases (${unrepresentable} not representable in UTF-8) -> ${path.pathname}`,
);
